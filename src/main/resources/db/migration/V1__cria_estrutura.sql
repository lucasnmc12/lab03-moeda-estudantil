-- Herança JOINED: PK da especialização também é FK da tabela base.
CREATE TABLE instituicao_ensino (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 senha_hash VARCHAR(100) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE aluno (
 id BIGINT PRIMARY KEY REFERENCES usuario(id),
 cpf VARCHAR(11) NOT NULL UNIQUE,
 rg VARCHAR(30) NOT NULL,
 endereco VARCHAR(250) NOT NULL,
 curso VARCHAR(120) NOT NULL,
 saldo INTEGER NOT NULL DEFAULT 0 CHECK (saldo >= 0),
 instituicao_id BIGINT NOT NULL REFERENCES instituicao_ensino(id)
);
CREATE TABLE professor (
 id BIGINT PRIMARY KEY REFERENCES usuario(id),
 cpf VARCHAR(11) NOT NULL UNIQUE,
 departamento VARCHAR(120) NOT NULL,
 saldo INTEGER NOT NULL DEFAULT 0 CHECK (saldo >= 0),
 instituicao_id BIGINT NOT NULL REFERENCES instituicao_ensino(id)
);
CREATE TABLE empresa_parceira (id BIGINT PRIMARY KEY REFERENCES usuario(id));
CREATE TABLE vantagem (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresa_parceira(id),
 descricao VARCHAR(500) NOT NULL,
 custo INTEGER NOT NULL CHECK (custo > 0),
 foto BLOB NOT NULL,
 foto_tipo VARCHAR(30) NOT NULL,
 ativa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE transacao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 data TIMESTAMP NOT NULL,
 quantidade INTEGER NOT NULL CHECK (quantidade > 0)
);
CREATE TABLE envio_moeda (
 id BIGINT PRIMARY KEY REFERENCES transacao(id),
 professor_id BIGINT NOT NULL REFERENCES professor(id),
 aluno_id BIGINT NOT NULL REFERENCES aluno(id),
 motivo VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(motivo)) > 0)
);
CREATE TABLE troca_vantagem (
 id BIGINT PRIMARY KEY REFERENCES transacao(id),
 aluno_id BIGINT NOT NULL REFERENCES aluno(id),
 vantagem_id BIGINT NOT NULL REFERENCES vantagem(id),
 codigo VARCHAR(36) NOT NULL UNIQUE,
 descricao_vantagem VARCHAR(500) NOT NULL,
 utilizada_em TIMESTAMP
);
CREATE TABLE credito_semestral (
 id BIGINT PRIMARY KEY REFERENCES transacao(id),
 professor_id BIGINT NOT NULL REFERENCES professor(id),
 semestre VARCHAR(6) NOT NULL,
 UNIQUE (professor_id, semestre)
);
CREATE TABLE notificacao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transacao_id BIGINT NOT NULL REFERENCES transacao(id),
 destinatario VARCHAR(180) NOT NULL,
 assunto VARCHAR(200) NOT NULL,
 texto VARCHAR(3000) NOT NULL,
 enviada_em TIMESTAMP,
 tentativas INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_envio_professor ON envio_moeda(professor_id);
CREATE INDEX idx_envio_aluno ON envio_moeda(aluno_id);
CREATE INDEX idx_troca_aluno ON troca_vantagem(aluno_id);
CREATE INDEX idx_vantagem_empresa ON vantagem(empresa_id);
CREATE INDEX idx_notificacao_pendente ON notificacao(enviada_em, id);
